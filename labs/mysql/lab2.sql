-- User-Defined Functions
--1. Create a function that takes actor_id and returns the concatenated first and last name of this actor.
delimiter /
CREATE FUNCTION get_actor_name(actor_id INT)
RETURNS VARCHAR(255)
not deterministic reads sql data
BEGIN
  DECLARE full_name VARCHAR(255);
  SELECT CONCAT(first_name, ' ', last_name) INTO full_name 
  FROM actor 
  WHERE actor.actor_id = actor_id;
  RETURN full_name;
END /
delimiter ;

--2. Create a function that takes customer_id and returns the total count of rentals made by this customer.
delimiter /
CREATE FUNCTION get_rental_count(customer_id INT)
RETURNS INT
not deterministic reads sql data
BEGIN
  DECLARE rental_count INT;
  SELECT COUNT(*) INTO rental_count 
  FROM rental 
  WHERE rental.customer_id = customer_id;
  RETURN rental_count;
END /
delimiter ;

--3. Create a function that takes a DECIMAL value and returns it as a formatted string with a dollar sign (e.g., $19.99).
delimiter /
CREATE FUNCTION format_currency(amount DECIMAL(10,2))
RETURNS VARCHAR(20)
not deterministic reads sql data
BEGIN
  RETURN CONCAT('$', FORMAT(amount, 2));
END /
delimiter ;

-- Stored Procedures
--4. Create a stored procedure that takes customer_id and returns a result set containing the full name, email, full address, and city of that customer.
delimiter /
CREATE PROCEDURE get_customer_info(IN cust_id INT)
BEGIN
  SELECT 
    CONCAT(first_name, ' ', last_name) AS full_name,
    email,
    CONCAT(address, ', ', city) AS full_address
  FROM customer 
  JOIN address ON customer.address_id = address.address_id 
  JOIN city ON address.city_id = city.city_id 
  WHERE customer.customer_id = cust_id;
END /
delimiter ;


--5. Create a stored procedure that takes a start_date and end_date and returns the total revenue generated by each store during that period.
delimiter /
CREATE PROCEDURE get_store_revenue(IN start_date DATE, IN end_date DATE)
BEGIN
  SELECT store_id, SUM(amount) AS total_revenue 
  FROM payment 
  WHERE payment_date BETWEEN start_date AND end_date 
  GROUP BY store_id;
END /
delimiter ;

--6. Create a stored procedure that takes a partial string (e.g., 'dark') and returns all films whose titles contain that string, along with their ratings.
delimiter /
CREATE PROCEDURE search_films_by_title(IN partial_title VARCHAR(255))
BEGIN
  SELECT title, rating 
  FROM film 
  WHERE title LIKE CONCAT('%', partial_title, '%');
END /
delimiter ;


--7. Create a stored procedure that takes customer_id and returns the name of the category (e.g., 'Action') that the customer rents most often.
delimiter /
CREATE PROCEDURE get_favorite_category(IN cust_id INT)
BEGIN
  SELECT category.name AS favorite_category
  FROM customer
  JOIN rental ON customer.customer_id = rental.customer_id
  JOIN inventory ON rental.inventory_id = inventory.inventory_id
  JOIN film ON inventory.film_id = film.film_id
  JOIN film_category ON film.film_id = film_category.film_id
  JOIN category ON film_category.category_id = category.category_id
  WHERE customer.customer_id = cust_id
  GROUP BY category.name
  ORDER BY COUNT(*) DESC
  LIMIT 1;
END /
delimiter ;


