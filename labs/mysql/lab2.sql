--9. Create a trigger to prevent an UPDATE to the staff table if the username is changed to 'admin'.
delimiter /
CREATE TRIGGER prevent_admin_username
BEFORE UPDATE ON staff
FOR EACH ROW
BEGIN
  IF NEW.username = 'admin' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Cannot change username to admin';
  END IF;
END /
delimiter ;


--10. Create a BEFORE INSERT trigger on the customer table to ensure that any email address entered contains both an @ and a . symbol.
delimiter /
CREATE TRIGGER validate_customer_email
BEFORE INSERT ON customer
FOR EACH ROW
BEGIN
  IF NEW.email NOT REGEXP '^[^@]+@[^@]+\.[^@]+$' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Invalid email format';
  END IF;
END /
delimiter ;


--11. Create a table film_price_history. Create an AFTER UPDATE trigger on the film table that records the old price, new price, and change date whenever the rental_rate is modified.
create table film_price_history (
  history_id INT AUTO_INCREMENT PRIMARY KEY,
  film_id INT,
  old_price DECIMAL(4,2),
  new_price DECIMAL(4,2),
  change_date DATETIME
);
delimiter /
CREATE TRIGGER record_price_change
AFTER UPDATE ON film
FOR EACH ROW
BEGIN
  IF OLD.rental_rate != NEW.rental_rate THEN
    INSERT INTO film_price_history (film_id, old_price, new_price, change_date)
    VALUES (NEW.film_id, OLD.rental_rate, NEW.rental_rate, NOW());
  END IF;
END /
delimiter ;
